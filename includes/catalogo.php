function encontrarTamanhos($request)
{
	global $lista_produtos;

	$chave_principal = $request['k'];
	$valor_selecionado = intval($request['i']);
	$forma = $request['forma'] ?? null;

	if (array_key_exists($chave_principal, $lista_produtos)) {

		$lista = ($forma && isset($lista_produtos[$chave_principal][$forma])) ? $lista_produtos[$chave_principal][$forma] : $lista_produtos[$chave_principal];

		if (isset($lista[$valor_selecionado])) {
			$produto = $lista[$valor_selecionado];

			echo json_encode(["tamanhos" => $produto["tamanhos"], "url" => $chave_principal]);
		} else {
			echo json_encode(["message" => "Produto inválido para a propriedade especificada."]);
		}
	} else {
		echo json_encode(["message" => "Produto não encontrado."]);
	}
}

function encontrarCores($request)
{
	global $lista_produtos;

	$chave_principal = $request['k'];
	$valor_selecionado = intval($request['i']);
	$sizeIndex = intval($request['sizeIndex']);
	$forma = $request['forma'] ?? null;

	if (array_key_exists($chave_principal, $lista_produtos)) {

		$lista = ($forma && isset($lista_produtos[$chave_principal][$forma])) ? $lista_produtos[$chave_principal][$forma] : $lista_produtos[$chave_principal];

		if (isset($lista[$valor_selecionado])) {
			$produto = $lista[$valor_selecionado];

			if (is_array($produto["cores"][$sizeIndex])) {
				echo json_encode(["cores" => $produto["cores"][$sizeIndex]]);
			} else {
				echo json_encode(["cores" => [$produto["cores"][$sizeIndex]]]);
			}
		} else {
			echo json_encode(["message" => "Cores inválido para a propriedade especificada."]);
		}
	} else {
		echo json_encode(["message" => "Cor não encontrado."]);
	}
}

