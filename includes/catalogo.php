function encontrarCor($key, $espessura = null, $tamanho, $forma = null)
{
	global $lista_produtos;

	$item_selecionado = $lista_produtos[$key];

	if ($forma && isset($item_selecionado[$forma])) {
		$item_selecionado = $item_selecionado[$forma];
	}

	$cores_encontradas = [];
	$encontrado = false;

	foreach ($item_selecionado as $variante) {
		if (!empty($espessura) && $variante["espessura"] != $espessura) {
			continue;
		}

		foreach ($variante["tamanhos"] as $index => $tamanho_atual) {
			if ($tamanho_atual == $tamanho) {
				$cores_atual = $variante["cores"][$index];
				if (is_array($cores_atual)) {
					$cores_encontradas = array_merge($cores_encontradas, $cores_atual);
				} else {
					$cores_encontradas[] = $cores_atual;
				}
				$encontrado = true;
				break 2; // Encontra a primeira correspondência e para a busca
			}
		}
	}

	// Remove duplicatas
	$cores_unicas = array_unique($cores_encontradas);

	if ($encontrado) {
		echo json_encode($cores_unicas);
	} else {
		echo json_encode(['error' => 'Cor não encontrada']);
	}
}


function encontrarValor($key, $espessura = null, $tamanho, $cor, $forma = null)
{
	global $lista_produtos;

	$item_selecionado = $lista_produtos[$key];

	if ($forma && isset($item_selecionado[$forma])) {
		$item_selecionado = $item_selecionado[$forma];
	}

	$valor_encontrado = null;

	foreach ($item_selecionado as $variante) {

		if (!empty($espessura) && $variante['espessura'] != $espessura) {
			continue;
		}


		foreach ($variante['tamanhos'] as $index => $tamanho_atual) {
			if ($tamanho_atual == $tamanho) {
				$cor_atual = $variante['cores'][$index];


				if ((is_array($cor_atual) && in_array($cor, $cor_atual)) || $cor_atual == $cor) {
					$valor_encontrado = $variante['valores'][$index];
					break 2;
				}
			}
		}
	}

	if ($valor_encontrado) {
		echo json_encode($valor_encontrado);
	} else {
		echo json_encode(['error' => 'Valor não encontrado']);
	}
}

function encontrarTamanho($key, $espessura = null, $forma = null)
{
	global $lista_produtos;

	$item_selecionado = $lista_produtos[$key];

	if ($forma && isset($item_selecionado[$forma])) {
		$item_selecionado = $item_selecionado[$forma];
	}

	$tamanhos_encontrados = [];

	foreach ($item_selecionado as $variante) {

		if (!empty($espessura) && $variante['espessura'] != $espessura) {
			continue;
		}

		foreach ($variante['tamanhos'] as $tamanho_atual) {
			if (!in_array($tamanho_atual, $tamanhos_encontrados)) {
				$tamanhos_encontrados[] = $tamanho_atual;
			}
		}
	}

	if (!empty($tamanhos_encontrados)) {
		echo json_encode($tamanhos_encontrados);
	} else {
		echo json_encode(['error' => 'Tamanho não encontrado']);
	}
}
